const {chromium} = require('C:/Users/User/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright');
const {execFileSync} = require('node:child_process');
const assert = require('node:assert/strict');
const path = require('node:path');
let browser;
(async () => {
  // Keep the server's credential in process memory; never print or write it.
  const token = execFileSync('ssh', ['-p','231','-i','C:/Users/User/.ssh/vps_fin','-o','BatchMode=yes','-o','StrictHostKeyChecking=yes','traen@2.26.66.48',"sed -n 's/^CRAWL4AI_API_TOKEN=//p' /home/traen/crawl4ai/.secrets.env"], {encoding:'utf8',timeout:20000}).trim();
  assert.equal(token.length,64);
  browser = await chromium.launch({headless:true,channel:'msedge'});
  const context = await browser.newContext({viewport:{width:1440,height:1000},permissions:['clipboard-read','clipboard-write']});
  const page = await context.newPage();
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto('https://aryseller.com/',{waitUntil:'networkidle'});
  assert.ok((await page.title()).includes('Arystan Seller'));
  await page.locator('a[href="/services/crawl4ai/"]').click();
  await page.waitForURL('https://aryseller.com/services/crawl4ai/');
  await page.locator('#availability-text').filter({hasText:'Сервис доступен'}).waitFor();
  await page.locator('#page-url').fill('https://example.com');
  await page.locator('#api-token').fill(token);
  await page.locator('#submit-button').click();
  await page.locator('#request-status').filter({hasText:'Готово:'}).waitFor({timeout:180000});
  const markdown = await page.locator('#result-content').innerText();
  assert.ok(markdown.toLowerCase().includes('documentation examples'));
  await page.locator('#copy-result').click();
  const clipboard = await page.evaluate(() => navigator.clipboard.readText());
  assert.equal(clipboard.replace(/\r\n/g,'\n'), markdown.replace(/\r\n/g,'\n'));
  const downloadWait = page.waitForEvent('download');
  await page.locator('#download-result').click();
  const download = await downloadWait;
  assert.equal(download.suggestedFilename(),'crawl4ai-result.md');
  await download.saveAs(path.join(process.argv[2],'live-crawl-result.md'));
  await page.locator('#clear-token').click();
  assert.equal(await page.evaluate(() => sessionStorage.getItem('aryseller.crawl4ai.token')),null);
  await page.screenshot({path:path.join(process.argv[2],'crawl4ai-live.png'),fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:path.join(process.argv[2],'crawl4ai-live-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[]);
  await browser.close();
  console.log('LIVE_BROWSER_OK: HTTPS company → service → authenticated real crawl → copy → download → clear credential; no page errors.');
})().catch(error => { console.error(error.message); process.exitCode = 1; }).finally(async () => { if (browser) await browser.close(); });
